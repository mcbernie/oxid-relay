//! systemd integration for Linux.
//!
//! Generates `/etc/systemd/system/oxid-relay.service` (the reference copy is
//! `packaging/systemd/oxid-relay.service`), creates the `oxid-relay` system
//! account and drives `systemctl`. All external commands go through a
//! [`CommandRunner`] so the call sequence is unit-testable.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::Context as _;

use super::ServiceManager;
use super::command::{CommandRunner, SystemRunner, run_checked};
use crate::layout::InstallLayout;
use crate::{SERVICE_DESCRIPTION, SERVICE_NAME};

/// Unprivileged account the service runs as.
pub const SERVICE_USER: &str = SERVICE_NAME;

/// Directory systemd loads administrator unit files from.
pub const UNIT_DIR: &str = "/etc/systemd/system";

/// Directory that exists only when systemd is the running init system.
const SYSTEMD_RUNTIME_DIR: &str = "/run/systemd/system";

/// Root under which `StateDirectory=` creates directories.
const STATE_ROOT: &str = "/var/lib";

/// Contents of a freshly created secrets file.
const ENV_FILE_TEMPLATE: &str = "\
# Secrets for oxid-relay, read by systemd as root (keep mode 0600).
# One KEY=value per line, for example:
# CLIENT_SECRET_AZURE=...
# TEAMS_WEBHOOK_URL=...
";

/// Unit file name, e.g. `oxid-relay.service`.
pub fn unit_name() -> String {
    format!("{SERVICE_NAME}.service")
}

/// Renders the systemd unit for `layout`.
///
/// Equivalent to `packaging/systemd/oxid-relay.service`, with paths taken
/// from the layout. A data directory below `/var/lib` is managed through
/// `StateDirectory=`; any other location is made writable with
/// `ReadWritePaths=` (needed because of `ProtectSystem=strict`).
pub fn unit_file(layout: &InstallLayout) -> String {
    let data_dir = layout.data_dir.display();
    let mut unit = String::new();
    // Writing to a String cannot fail.
    let _ = write!(
        unit,
        "\
# Generated by `oxid-relay install`; changes are overwritten on reinstall.
[Unit]
Description={SERVICE_DESCRIPTION}
Documentation=https://github.com/{repo}
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart={binary} --config {config}
Environment=OXID_RELAY_PLUGIN_DIR={plugins}
",
        repo = crate::GITHUB_REPO,
        binary = layout.binary.display(),
        config = layout.config_file.display(),
        plugins = layout.plugin_dir.display(),
    );
    if let Some(env_file) = &layout.env_file {
        let _ = writeln!(
            unit,
            "\n# Secrets (CLIENT_SECRET_AZURE, TEAMS_WEBHOOK_URL, ...); mode 0600, owned by root.\n\
             EnvironmentFile=-{}",
            env_file.display()
        );
    }
    let _ = write!(
        unit,
        "
Restart=on-failure
RestartSec=5

User={SERVICE_USER}
Group={SERVICE_USER}

# The queue database lives in the working directory.
"
    );
    match layout.data_dir.strip_prefix(STATE_ROOT) {
        Ok(relative) if !relative.as_os_str().is_empty() => {
            let _ = writeln!(unit, "StateDirectory={}", relative.display());
        }
        _ => {
            let _ = writeln!(unit, "ReadWritePaths={data_dir}");
        }
    }
    let _ = write!(
        unit,
        "\
WorkingDirectory={data_dir}

# Hardening.
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
PrivateTmp=true
ProtectControlGroups=true
ProtectKernelTunables=true
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX

[Install]
WantedBy=multi-user.target
"
    );
    unit
}

/// systemd service manager.
pub struct Systemd<R: CommandRunner = SystemRunner> {
    runner: R,
    unit_dir: PathBuf,
}

impl Systemd {
    /// The real systemd, or an error if systemd is not the init system.
    pub fn detect() -> anyhow::Result<Self> {
        if !Path::new(SYSTEMD_RUNTIME_DIR).is_dir() {
            anyhow::bail!(
                "systemd not found ({SYSTEMD_RUNTIME_DIR} is missing); \
                 `oxid-relay install` only supports systemd-based Linux systems"
            );
        }
        Ok(Self::with_runner(SystemRunner, PathBuf::from(UNIT_DIR)))
    }
}

impl<R: CommandRunner> Systemd<R> {
    /// A manager using `runner` for commands and writing units to `unit_dir`.
    pub fn with_runner(runner: R, unit_dir: PathBuf) -> Self {
        Self { runner, unit_dir }
    }

    /// The command runner (lets tests inspect recorded calls).
    pub fn runner(&self) -> &R {
        &self.runner
    }

    /// Full path of the unit file.
    pub fn unit_path(&self) -> PathBuf {
        self.unit_dir.join(unit_name())
    }

    fn systemctl(&self, args: &[&str]) -> anyhow::Result<()> {
        run_checked(&self.runner, "systemctl", args).map(drop)
    }

    fn user_exists(&self) -> anyhow::Result<bool> {
        Ok(self.runner.run("id", &["-u", SERVICE_USER])?.success)
    }

    /// Creates the system account (with a group of the same name) if missing.
    fn ensure_user(&self, layout: &InstallLayout) -> anyhow::Result<()> {
        if self.user_exists()? {
            return Ok(());
        }
        let home = layout.data_dir.to_string_lossy();
        run_checked(
            &self.runner,
            "useradd",
            &[
                "--system",
                "--user-group",
                "--home",
                &home,
                "--shell",
                "/usr/sbin/nologin",
                SERVICE_USER,
            ],
        )
        .context("creating the service account")?;
        Ok(())
    }

    /// Lets the service account read `config.toml` (root keeps write access).
    fn share_config(&self, layout: &InstallLayout) -> anyhow::Result<()> {
        if !layout.config_file.exists() {
            return Ok(());
        }
        let config = layout.config_file.to_string_lossy();
        let owner = format!("root:{SERVICE_USER}");
        run_checked(&self.runner, "chown", &[&owner, &config])?;
        run_checked(&self.runner, "chmod", &["0640", &config])?;
        Ok(())
    }
}

impl<R: CommandRunner> ServiceManager for Systemd<R> {
    fn register(&self, layout: &InstallLayout) -> anyhow::Result<()> {
        self.ensure_user(layout)?;

        let unit_path = self.unit_path();
        std::fs::create_dir_all(&self.unit_dir)
            .with_context(|| format!("creating {}", self.unit_dir.display()))?;
        std::fs::write(&unit_path, unit_file(layout))
            .with_context(|| format!("writing {}", unit_path.display()))?;

        if let Some(env_file) = &layout.env_file {
            create_env_file(env_file)?;
        }
        self.share_config(layout)?;

        self.systemctl(&["daemon-reload"])?;
        self.systemctl(&["enable", &unit_name()])
    }

    fn unregister(&self) -> anyhow::Result<()> {
        if !self.is_registered()? {
            return Ok(());
        }
        self.systemctl(&["disable", &unit_name()])?;
        let unit_path = self.unit_path();
        std::fs::remove_file(&unit_path)
            .with_context(|| format!("removing {}", unit_path.display()))?;
        self.systemctl(&["daemon-reload"])
    }

    fn start(&self) -> anyhow::Result<()> {
        self.systemctl(&["start", &unit_name()])
            .with_context(|| format!("starting the service; see `journalctl -u {SERVICE_NAME} -e`"))
    }

    fn stop(&self) -> anyhow::Result<()> {
        if !self.is_registered()? {
            return Ok(());
        }
        self.systemctl(&["stop", &unit_name()])
    }

    fn is_running(&self) -> anyhow::Result<bool> {
        let output = self
            .runner
            .run("systemctl", &["is-active", "--quiet", &unit_name()])?;
        Ok(output.success)
    }

    fn is_registered(&self) -> anyhow::Result<bool> {
        Ok(self.unit_path().exists())
    }

    fn purge(&self) -> anyhow::Result<()> {
        if self.user_exists()? {
            run_checked(&self.runner, "userdel", &[SERVICE_USER])
                .context("removing the service account")?;
        }
        Ok(())
    }
}

/// Creates an empty secrets file with mode 0600 unless one already exists.
/// The installer runs as root, so the file is owned by root; systemd reads
/// `EnvironmentFile=` before dropping privileges.
fn create_env_file(path: &Path) -> anyhow::Result<()> {
    use std::io::Write as _;
    use std::os::unix::fs::OpenOptionsExt as _;

    if path.exists() {
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
    }
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(path)
        .with_context(|| format!("creating {}", path.display()))?;
    file.write_all(ENV_FILE_TEMPLATE.as_bytes())
        .with_context(|| format!("writing {}", path.display()))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::os::unix::fs::PermissionsExt as _;

    use super::*;
    use crate::service::command::fake::FakeRunner;

    /// A Linux-shaped layout rooted in `root`.
    fn temp_layout(root: &Path) -> InstallLayout {
        let config_dir = root.join("etc");
        InstallLayout {
            bin_dir: root.join("bin"),
            binary: root.join("bin/oxid-relay"),
            config_file: config_dir.join("config.toml"),
            plugin_dir: config_dir.join("plugins"),
            env_file: Some(config_dir.join("oxid-relay.env")),
            config_dir,
            data_dir: root.join("data"),
        }
    }

    #[test]
    fn unit_file_for_default_layout() {
        let unit = unit_file(&InstallLayout::linux());
        for line in [
            "ExecStart=/usr/local/bin/oxid-relay --config /etc/oxid-relay/config.toml",
            "Environment=OXID_RELAY_PLUGIN_DIR=/etc/oxid-relay/plugins",
            "EnvironmentFile=-/etc/oxid-relay/oxid-relay.env",
            "User=oxid-relay",
            "Group=oxid-relay",
            "StateDirectory=oxid-relay",
            "WorkingDirectory=/var/lib/oxid-relay",
            "ProtectSystem=strict",
            "NoNewPrivileges=true",
            "Restart=on-failure",
            "WantedBy=multi-user.target",
        ] {
            assert!(
                unit.lines().any(|l| l == line),
                "missing `{line}` in:\n{unit}"
            );
        }
        assert!(!unit.contains("ReadWritePaths="));
    }

    #[test]
    fn unit_file_outside_var_lib_uses_read_write_paths() {
        let layout = InstallLayout {
            data_dir: PathBuf::from("/srv/relay"),
            env_file: None,
            ..InstallLayout::linux()
        };
        let unit = unit_file(&layout);
        assert!(unit.contains("ReadWritePaths=/srv/relay\n"));
        assert!(unit.contains("WorkingDirectory=/srv/relay\n"));
        assert!(!unit.contains("StateDirectory="));
        assert!(!unit.contains("EnvironmentFile="));
    }

    #[test]
    fn register_creates_user_unit_and_env_file() {
        let dir = tempfile::tempdir().unwrap();
        let layout = temp_layout(dir.path());
        std::fs::create_dir_all(&layout.config_dir).unwrap();
        std::fs::write(&layout.config_file, "").unwrap();
        // `id -u` fails: the account does not exist yet.
        let runner = FakeRunner::with(|line| !line.starts_with("id "));
        let systemd = Systemd::with_runner(runner, dir.path().join("units"));

        systemd.register(&layout).unwrap();

        let config = layout.config_file.display().to_string();
        let home = layout.data_dir.display().to_string();
        assert_eq!(
            systemd.runner().calls(),
            vec![
                "id -u oxid-relay".to_string(),
                format!(
                    "useradd --system --user-group --home {home} --shell /usr/sbin/nologin oxid-relay"
                ),
                format!("chown root:oxid-relay {config}"),
                format!("chmod 0640 {config}"),
                "systemctl daemon-reload".to_string(),
                "systemctl enable oxid-relay.service".to_string(),
            ]
        );
        let unit = std::fs::read_to_string(systemd.unit_path()).unwrap();
        assert_eq!(unit, unit_file(&layout));
        let env_file = layout.env_file.as_ref().unwrap();
        let mode = std::fs::metadata(env_file).unwrap().permissions().mode();
        assert_eq!(mode & 0o777, 0o600);
    }

    #[test]
    fn register_keeps_existing_user_and_env_file() {
        let dir = tempfile::tempdir().unwrap();
        let layout = temp_layout(dir.path());
        let env_file = layout.env_file.clone().unwrap();
        std::fs::create_dir_all(&layout.config_dir).unwrap();
        std::fs::write(&env_file, "SECRET=1\n").unwrap();
        let systemd = Systemd::with_runner(FakeRunner::ok(), dir.path().join("units"));

        systemd.register(&layout).unwrap();

        assert_eq!(
            systemd.runner().calls(),
            vec![
                "id -u oxid-relay",
                "systemctl daemon-reload",
                "systemctl enable oxid-relay.service",
            ]
        );
        assert_eq!(std::fs::read_to_string(env_file).unwrap(), "SECRET=1\n");
    }

    #[test]
    fn register_fails_with_stderr_when_useradd_fails() {
        let dir = tempfile::tempdir().unwrap();
        let layout = temp_layout(dir.path());
        let runner =
            FakeRunner::with(|line| !line.starts_with("id ") && !line.starts_with("useradd"));
        let systemd = Systemd::with_runner(runner, dir.path().join("units"));

        let err = systemd.register(&layout).unwrap_err();
        assert!(format!("{err:#}").contains("creating the service account"));
        assert!(format!("{err:#}").contains("boom"));
    }

    #[test]
    fn stop_and_unregister_are_noops_when_not_registered() {
        let dir = tempfile::tempdir().unwrap();
        let systemd = Systemd::with_runner(FakeRunner::ok(), dir.path().to_path_buf());
        systemd.stop().unwrap();
        systemd.unregister().unwrap();
        assert!(systemd.runner().calls().is_empty());
    }

    #[test]
    fn lifecycle_command_sequence() {
        let dir = tempfile::tempdir().unwrap();
        let systemd = Systemd::with_runner(FakeRunner::ok(), dir.path().to_path_buf());
        std::fs::write(systemd.unit_path(), "").unwrap();

        systemd.start().unwrap();
        assert!(systemd.is_running().unwrap());
        systemd.stop().unwrap();
        systemd.unregister().unwrap();
        systemd.purge().unwrap();

        assert!(!systemd.unit_path().exists());
        assert_eq!(
            systemd.runner().calls(),
            vec![
                "systemctl start oxid-relay.service",
                "systemctl is-active --quiet oxid-relay.service",
                "systemctl stop oxid-relay.service",
                "systemctl disable oxid-relay.service",
                "systemctl daemon-reload",
                "id -u oxid-relay",
                "userdel oxid-relay",
            ]
        );
    }

    #[test]
    fn is_running_false_when_inactive() {
        let dir = tempfile::tempdir().unwrap();
        let systemd = Systemd::with_runner(FakeRunner::with(|_| false), dir.path().to_path_buf());
        assert!(!systemd.is_running().unwrap());
    }
}
